import Capacitor

@UIApplicationMain
class AppDelegate: UIResponder, UIApplicationDelegate {

    var window: UIWindow?

    func application(_ application: UIApplication, didFinishLaunchingWithOptions launchOptions: [UIApplication.LaunchOptionsKey: Any]?) -> Bool {
        // Override point for customization after application launch.
        return true
    }

    // A miniatura do selector de apps é tirada depois disto: com a vista opaca
    // por cima, os números do ecrã não ficam lá à vista.
    private let tagDaCortina = 0x4C42

    func applicationWillResignActive(_ application: UIApplication) {
        guard let window = window, window.viewWithTag(tagDaCortina) == nil else { return }
        let cortina = UIView(frame: window.bounds)
        cortina.tag = tagDaCortina
        cortina.backgroundColor = .systemBackground
        cortina.autoresizingMask = [.flexibleWidth, .flexibleHeight]
        window.addSubview(cortina)
    }

    func applicationDidEnterBackground(_ application: UIApplication) {
